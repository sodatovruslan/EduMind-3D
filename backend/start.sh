#!/usr/bin/env sh
# Прогон миграций перед стартом веб-процесса: на managed-хостинге нет отдельного
# release-шага, а база при первом деплое пустая. Alembic идемпотентен — на
# последующих рестартах upgrade head просто ничего не делает.
set -e

echo "[start] alembic upgrade head"
alembic upgrade head

# Каталог лабораторий — это контент продукта, а не тестовые данные: без записей
# в simulations дашборд показывает «Скоро» на всех трёх карточках, и зайти
# некуда. Миграциями он не создаётся, отдельного release-шага на Render нет,
# а Shell на бесплатном плане недоступен — поэтому сеем на старте. Скрипт
# идемпотентен (пропускает существующие по title). Включён по умолчанию,
# чтобы свежий деплой поднимался рабочим без ручных шагов; выключается
# через SEED_SIMULATIONS=false, если каталогом начнут управлять вручную —
# иначе переименованный урок воскреснет дубликатом на ближайшем рестарте.
if [ "${SEED_SIMULATIONS:-true}" = "true" ]; then
  echo "[start] seed simulations"
  python seed_simulations.py
fi

echo "[start] uvicorn on 0.0.0.0:${PORT:-8000}"
# Один воркер сознательно: реестр WS-соединений (app/core/ws_manager.py)
# не разделяется между процессами, на двух воркерах часть сообщений и
# presence-событий не доедет до получателя.
exec uvicorn app.main:app --host 0.0.0.0 --port "${PORT:-8000}" --workers 1
